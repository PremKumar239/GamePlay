-- GAME PLAY schema for local PostgreSQL / pgAdmin.
-- Open the GamePlay database in pgAdmin → Query Tool → paste and run this whole file.

create extension if not exists pgcrypto;

create table if not exists public.products (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null,
  group_name text,
  subcategory text,
  image_key text not null default 'remote',
  image_url text,
  price integer not null check (price >= 0),
  old_price integer,
  badge text,
  description text not null default '',
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated always as identity primary key,
  name text not null unique,
  label text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.subcategories (
  id bigint generated always as identity primary key,
  category_id bigint not null references public.categories (id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  unique (category_id, name)
);

create table if not exists public.orders (
  id bigint generated always as identity primary key,
  order_number text not null unique,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  customer_address text,
  notes text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipped', 'completed', 'cancelled')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid', 'paid', 'refunded')),
  payment_method text not null default 'whatsapp',
  total integer not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  product_id integer references public.products (id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price integer not null check (unit_price >= 0),
  line_total integer not null check (line_total >= 0)
);

create table if not exists public.contact_messages (
  id bigint generated always as identity primary key,
  customer_name text not null default '',
  customer_email text,
  customer_phone text,
  message text not null,
  status text not null default 'new' check (status in ('new', 'read', 'replied', 'archived')),
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  store_name text not null default 'GAME PLAY',
  phone text not null default '0323 5551600',
  whatsapp_number text not null default '923235551600',
  address text not null default '1st Floor, 66B, Sector C Commercial Area, Bahria Town, Lahore, 56000, Pakistan',
  closing_time text not null default '11:30 PM',
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.tax_settings (
  id integer primary key default 1 check (id = 1),
  card_tax_percent numeric(6, 2) not null default 0 check (card_tax_percent >= 0 and card_tax_percent <= 100),
  cod_tax_percent numeric(6, 2) not null default 0 check (cod_tax_percent >= 0 and cod_tax_percent <= 100),
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  id bigint generated always as identity primary key,
  email text not null unique,
  password_hash text not null,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists contact_messages_created_at_idx on public.contact_messages (created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at before update on public.products
for each row execute function public.touch_updated_at();
drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at before update on public.orders
for each row execute function public.touch_updated_at();
drop trigger if exists settings_touch_updated_at on public.store_settings;
create trigger settings_touch_updated_at before update on public.store_settings
for each row execute function public.touch_updated_at();
drop trigger if exists tax_settings_touch_updated_at on public.tax_settings;
create trigger tax_settings_touch_updated_at before update on public.tax_settings
for each row execute function public.touch_updated_at();

